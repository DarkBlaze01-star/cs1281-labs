import random
import time

def introduction():
    print("=" * 50)
    print("       WELCOME TO THE PY-QUEST ADVENTURE!       ")
    print("=" * 50)
    print("You are a brave coder entering the Dungeon of Bugs to retrieve")
    print("the legendary 'Golden Syntax Error-Free Compiler'.")
    print("-" * 50)

def get_valid_choice(options):
    while True:
        try:
            choice = int(input(f"Enter your choice (1-{len(options)}): "))
            if 1 <= choice <= len(options):
                return choice
            else:
                print(f"Invalid range! Please choose a number between 1 and {len(options)}.")
        except ValueError:
            print("Invalid input! Please enter a valid number.")

def shop(player):
    print("\n--- Welcome to the Developer Shop! ---")
    print(f"Your Gold: {player['gold']}")
    items_for_sale = {
        "1": {"name": "Health Potion", "cost": 20, "heal": 30},
        "2": {"name": "Super Coffee", "cost": 40, "heal": 60}
    }

    for key, item in items_for_sale.items():
        print(f"{key}. {item['name']} - Cost: {item['cost']} Gold (Heals {item['heal']} HP)")
    print("3. Leave Shop")

    choice = get_valid_choice([1, 2, 3])
    if choice in [1, 2]:
        item_key = str(choice)
        selected_item = items_for_sale[item_key]
        if player['gold'] >= selected_item['cost']:
            player['gold'] -= selected_item['cost']
            player['inventory'].append(selected_item['name'])
            print(f"\nSuccess! You bought a {selected_item['name']}.")
        else:
            print("\nNot enough gold!")
    else:
        print("\nYou left the shop.")

def use_item(player):
    if not player['inventory']:
        print("\nYour inventory is empty!")
        return

    print("\n--- Your Inventory ---")
    for index, item in enumerate(player['inventory'], 1):
        print(f"{index}. {item}")
    print(f"{len(player['inventory']) + 1}. Cancel")

    choice = get_valid_choice(range(1, len(player['inventory']) + 2))
    if choice <= len(player['inventory']):
        removed_item = player['inventory'].pop(choice - 1)
        if "Coffee" in removed_item:
            heal_amount = 60
        else:
            heal_amount = 30

        player['hp'] = min(100, player['hp'] + heal_amount)
        print(f"\nYou used {removed_item} and restored {heal_amount} HP! (Current HP: {player['hp']}/100)")

def battle(player):
    enemies = [
        {"name": "Syntax Error Goblin", "hp": 40, "damage": 10, "gold": 15},
        {"name": "Infinite Loop Slime", "hp": 50, "damage": 15, "gold": 25},
        {"name": "Null Pointer Dragon", "hp": 80, "damage": 20, "gold": 50}
    ]

    enemy = random.choice(enemies)
    print(f"\n⚠️ A wild {enemy['name']} appeared! (HP: {enemy['hp']}, Atk: {enemy['damage']})")

    while enemy['hp'] > 0 and player['hp'] > 0:
        print(f"\nYour HP: {player['hp']}/100 | {enemy['name']} HP: {enemy['hp']}")
        print("What will you do?")
        print("1. Attack with Code")
        print("2. Use Item")
        print("3. Run away")

        choice = get_valid_choice([1, 2, 3])

        if choice == 1:
            damage = random.randint(15, 30)
            enemy['hp'] -= damage
            print(f"\nYou executed a flawless script! You dealt {damage} damage to {enemy['name']}.")
        elif choice == 2:
            use_item(player)
            continue
        else:
            if random.random() > 0.5:
                print("\nYou successfully escaped the battle!")
                return
            else:
                print("\nFailed to escape! The enemy blocks your exit!")

        if enemy['hp'] > 0:
            enemy_dmg = random.randint(5, enemy['damage'])
            player['hp'] -= enemy_dmg
            print(f"The {enemy['name']} attacks back, dealing {enemy_dmg} damage to you!")

    if player['hp'] <= 0:
        print("\n💀 Game Over! You were defeated by the bugs. Keep practicing your Python syntax!")
    else:
        player['gold'] += enemy['gold']
        print(f"\n🎉 Victory! You defeated the {enemy['name']} and found {enemy['gold']} gold!")

def play_game():
    player = {
        "hp": 100,
        "gold": 30,
        "inventory": ["Health Potion"]
    }

    introduction()

    while player['hp'] > 0:
        print("\n" + "="*40)
        print(f"STATUS: HP: {player['hp']}/100 | Gold: {player['gold']} | Inventory: {player['inventory']}")
        print("="*40)
        print("What is your next move?")
        print("1. Search for bugs to fight (Battle)")
        print("2. Visit the Developer Shop")
        print("3. Check/Use Items from Inventory")
        print("4. Quit Game")

        choice = get_valid_choice([1, 2, 3, 4])

        if choice == 1:
            battle(player)
        elif choice == 2:
            shop(player)
        elif choice == 3:
            use_item(player)
        else:
            print("\nThank you for playing Py-Quest! Congratulations on completing your 10 Python labs!")
            break

# Start the game
play_game()