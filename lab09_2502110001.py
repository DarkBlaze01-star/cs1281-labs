import os
import re

# 1. Setup the data directory and generate input test data (IT12)
os.makedirs('data', exist_ok=True)

log_data = """PE-0137,25.02,DAY
PE-0201,24.90,NIGHT
PE-0345,25.04,DAY, re-gauged
PE-0512, invalid_val, DAY
PE-0620,26.15,SWING
PE-0789,24.88,NIGHT
PE-0999,25.00,SWING
PE-1024,25.50,DAY
PE-1150,,NIGHT
PE-1233,24.75,SWING
PE-1345,25.10,DAY
PE-1499,23.95,NIGHT
BAD_CODE,25.00,DAY
PE-1670,25.30,SWING
PE-1801,24.65,DAY
"""

with open('data/shift_log.txt', 'w', encoding='utf-8') as f:
    f.write(log_data)

print("-> data/shift_log.txt created successfully.")

# 2. READ the file from disk using a relative path
with open('data/shift_log.txt', 'r', encoding='utf-8') as f:
    lines = f.readlines()

valid_records = []
rejects = []

# Regex pattern to match valid codes and numbers
pattern = re.compile(r'^(PE-\d{4})\s*,\s*([\d.]+)\s*,\s*(DAY|NIGHT|SWING)')

# 3. PARSE & VALIDATE line by line
for line_num, line in enumerate(lines, 1):
    line = line.strip()
    if not line:
        continue

    match = pattern.match(line)
    if match:
        code, reading, shift = match.groups()
        try:
            val = float(reading)
            valid_records.append({'code': code, 'value': val, 'shift': shift})
        except ValueError:
            rejects.append(f"Line {line_num}: Invalid number format -> {line}")
    else:
        rejects.append(f"Line {line_num}: Regex mismatch -> {line}")

# 4. AGGREGATE totals and averages
total_records = len(valid_records)
sum_values = sum(r['value'] for r in valid_records)
avg_value = sum_values / total_records if total_records > 0 else 0

# 5. WRITE results back to disk
with open('data/report.txt', 'w', encoding='utf-8') as f:
    f.write("=== SHIFT PRODUCTION REPORT ===\n")
    f.write(f"Total Valid Records: {total_records}\n")
    f.write(f"Average Reading:     {avg_value:.2f}\n")

with open('data/rejects.csv', 'w', encoding='utf-8') as f:
    f.write("Reason\n")
    for rej in rejects:
        f.write(f"{rej}\n")

print("-> Pipeline execution complete.")
print("-> Generated: data/report.txt and data/rejects.csv")